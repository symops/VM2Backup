#!/usr/bin/env python3
"""Turns src/web/* into src/webui.inc: every file as byte arrays (raw + gzip) and a table the web server serves from memory.
Run:  python3 tools/gen_webui.py   (the output is deterministic; the exe needs no files next to it)"""
import gzip, os

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(root, 'src', 'web')
out = os.path.join(root, 'src', 'webui.inc')
types = {'.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8',
         '.svg': 'image/svg+xml', '.json': 'application/json', '.txt': 'text/plain; charset=utf-8'}

def arr(name, data):
    lines = [','.join(str(b) for b in data[i:i + 24]) for i in range(0, len(data), 24)]
    return 'static const unsigned char %s[] = {\n%s\n};\n' % (name, ',\n'.join(lines) if lines else '0')

import json, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import webui_strings
# one small script per language (src/web/lang/<code>.txt -> /lang/<code>.js); the page loads only the one it needs
def lang_js(code):
    table, _ = webui_strings.read_lang(code)
    t = {k: v for k, v in table.items() if v}
    body = json.dumps(t, ensure_ascii=False, separators=(',', ':'), sort_keys=True).replace('\u2028', '\\u2028').replace('\u2029', '\\u2029')
    return ('window.VM2B_STRINGS=window.VM2B_STRINGS||{};window.VM2B_STRINGS[%s]=%s;\n' % (json.dumps(code), body)).encode('utf-8')
entries = [(f, open(os.path.join(src, f), 'rb').read()) for f in sorted(f for f in os.listdir(src) if os.path.isfile(os.path.join(src, f)))]
entries += [('lang/%s.js' % c, lang_js(c)) for c, _ in webui_strings.LANGS if c != 'en']
files = [e[0] for e in entries]
parts = ['// Generated by tools/gen_webui.py from src/web/* - do not edit.\n']
table = []
for i, f in enumerate(files):
    data = entries[i][1]
    gz = gzip.compress(data, 9, mtime=0)
    parts.append(arr('webui_raw_%d' % i, data))
    parts.append(arr('webui_gz_%d' % i, gz))
    ext = os.path.splitext(f)[1]
    table.append('    { "/%s", "%s", webui_raw_%d, %d, webui_gz_%d, %d },' % (f, types.get(ext, 'application/octet-stream'), i, len(data), i, len(gz)))
parts.append('struct WebUiFile { const char* path; const char* type; const unsigned char* raw; unsigned rawLen; const unsigned char* gz; unsigned gzLen; };\n')
parts.append('static const WebUiFile kWebUi[] = {\n%s\n};\nstatic const int kWebUiCount = %d;\n' % ('\n'.join(table), len(table)))
open(out, 'w').write(''.join(parts))
print('wrote', out, len(files), 'files')
