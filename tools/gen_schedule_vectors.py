#!/usr/bin/env python3
"""Writes src/tests_schedule_vectors.inc: random schedules with the answers of the Python reference (pyref/vm2backup/schedule.py).
The C++ schedule.cpp must give the same next run for every case (tests/native/t_schedule.cpp and the autotest "schedule").
    python3 tools/gen_schedule_vectors.py [seed]
"""
import json, os, random, sys
from datetime import datetime, timedelta
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'pyref'))
from vm2backup.schedule import next_run

EPOCH = datetime(1970, 1, 1)
def to_min(dt): return int((dt - EPOCH).total_seconds() // 60)
rnd = random.Random(int(sys.argv[1]) if len(sys.argv) > 1 else 20261024)
cases = []
def rdt():
    return datetime(2024, 1, 1) + timedelta(minutes=rnd.randrange(0, 60 * 24 * 365 * 4))
def iso(dt): return dt.strftime('%Y-%m-%dT%H:%M')
for _ in range(400):
    mode = rnd.choice(['every', 'weekly', 'monthly', 'once'])
    sp = {'enabled': True, 'mode': mode}
    if mode == 'every':
        sp['every'] = {'value': rnd.randint(1, 50), 'unit': rnd.choice(['minutes', 'hours', 'days'])}
        sp['first_time'] = iso(rdt())
    elif mode == 'weekly':
        sp['start_time'] = '%02d:%02d' % (rnd.randrange(24), rnd.randrange(60))
        sp['weekdays'] = sorted(rnd.sample(range(7), rnd.randint(1, 7)))
        sp['week_interval'] = rnd.choice([1, 1, 2, 3, 4])
        if rnd.random() < .5: sp['anchor'] = rdt().strftime('%Y-%m-%d')
    elif mode == 'monthly':
        sp['start_time'] = '%02d:%02d' % (rnd.randrange(24), rnd.randrange(60))
        sp['day'] = rnd.choice(['last', 1, 15, 28, 29, 30, 31, rnd.randint(1, 31)])
        sp['month_interval'] = rnd.choice([1, 1, 2, 3, 6, 12])
    else:
        sp['at'] = iso(rdt())
    after = rdt()
    r = next_run(sp, after)
    cases.append({'sp': sp, 'after': to_min(after), 'next': to_min(r) if r else None})
# a few disabled / edge ones
cases.append({'sp': {'enabled': False, 'mode': 'every'}, 'after': 0, 'next': None})
out = os.path.join(HERE, '..', 'src', 'tests_schedule_vectors.inc')
open(out, 'w').write('// generated by tools/gen_schedule_vectors.py - do not edit\nstatic const char kScheduleVectors[] = R"JSON(' + json.dumps(cases, separators=(',', ':')) + ')JSON";\n')
print('wrote', len(cases), 'cases to', out)
